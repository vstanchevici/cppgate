#!/usr/bin/env python3
"""
Regenerates sources/Client/CaBundle.cpp from curl's copy of the Mozilla CA store.

    python3 tools/update_ca_bundle.py

Downloads https://curl.se/ca/cacert.pem, checks it against the published SHA-256 and writes the
certificates as C++ string literals. Run it now and then (Mozilla adds and removes CAs), rebuild,
and commit the result.
"""

import hashlib
import pathlib
import re
import sys
import urllib.request

BUNDLE_URL = "https://curl.se/ca/cacert.pem"
SHA256_URL = "https://curl.se/ca/cacert.pem.sha256"
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "sources" / "Client" / "CaBundle.cpp"

# MSVC rejects string literals over ~16 KB: split the bundle, at certificate boundaries
MAX_PART = 15000


def download(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()


def main():
    pem = download(BUNDLE_URL)
    expected = download(SHA256_URL).decode().split()[0].lower()
    actual = hashlib.sha256(pem).hexdigest()
    if actual != expected:
        sys.exit(f"SHA-256 mismatch: got {actual}, curl.se publishes {expected}")

    text = pem.decode("utf-8")
    date = re.search(r"Certificate data from Mozilla as of: (.+)", text)
    date = date.group(1).strip() if date else "unknown"

    certificates = re.findall(r"-----BEGIN CERTIFICATE-----\n.+?\n-----END CERTIFICATE-----\n", text, re.S)
    if len(certificates) < 50:
        sys.exit(f"Only {len(certificates)} certificates found, refusing to write a suspicious bundle")

    parts, current = [], ""
    for certificate in certificates:
        if current and len(current) + len(certificate) > MAX_PART:
            parts.append(current)
            current = ""
        current += certificate
    parts.append(current)

    lines = [
        "// Generated by tools/update_ca_bundle.py from https://curl.se/ca/cacert.pem, do not edit.",
        f"// Mozilla CA certificate store as of {date}, {len(certificates)} certificates, SHA-256 {actual}.",
        "// The certificate data is licensed under the Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/).",
        "",
        "#include <cstddef>",
        "",
        "namespace gtvr::detail {",
        "",
        "    extern const char* const ca_bundle_parts[] = {",
    ]
    for part in parts:
        lines.append(f'R"PEM({part})PEM",')
    lines += [
        "    };",
        "",
        "    extern const std::size_t ca_bundle_part_count = sizeof(ca_bundle_parts) / sizeof(ca_bundle_parts[0]);",
        "",
        f'    extern const char* const ca_bundle_date = "{date}";',
        "",
        f"    extern const std::size_t ca_bundle_certificate_count = {len(certificates)};",
        "",
        "}//namespace gtvr::detail",
        "",
    ]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"{OUTPUT}: {len(certificates)} certificates in {len(parts)} parts, Mozilla data as of {date}")


if __name__ == "__main__":
    main()
